"""Synthetic US household profile generator.

Profiles are parameterizable synthetic applicant households. They are the
"who is asking" half of every test case.

All names and addresses are generated by Faker — no real PII ever.
Income and household distributions are modeled on Census ACS microdata.
"""

from __future__ import annotations

import random
from dataclasses import dataclass, field
from functools import lru_cache
from statistics import NormalDist
from typing import TYPE_CHECKING, Any

from faker import Faker

from govsynth.models.enums import CitizenshipStatus

if TYPE_CHECKING:
    from govsynth.sources.us.census import CensusDistribution, CensusVintage
    from govsynth.sources.us.household_types import HouseholdTypes

_faker = Faker("en_US")

POPULATIONS = ("general", "caseload")

# See `USHouseholdProfile.natural_language_summary_styled`. Named as a public
# constant, not a magic set of strings scattered at call sites, so a caller
# building a diverse corpus can iterate `PHRASING_STYLES` to get all of them
# rather than hardcoding a list that could silently drift from what the method
# actually implements.
PHRASING_STYLES: tuple[str, ...] = ("caseworker_note", "narrative", "terse", "conversational", "formal")

# See `USHouseholdProfile.generate_scenario_question_styled`. Question phrasing styles
# for eligibility scenarios -- all ask the same underlying question but from
# different angles/registers, supporting semantic variation for RLVR training.
SCENARIO_PHRASING_STYLES: tuple[str, ...] = (
    "direct",
    "exploratory",
    "constraint_focused",
    "outcome_focused",
    "policy_grounded",
)


@dataclass
class USHouseholdProfile:
    """A synthetic US household applicant profile.

    Fields map directly to ScenarioBlock fields for easy conversion.
    """

    # Core eligibility fields
    household_size: int
    monthly_gross_income: float
    state: str

    # Optional but commonly needed
    monthly_net_income: float | None = None
    liquid_assets: float = 0.0
    has_elderly_or_disabled: bool = False
    has_dependent_children: bool = False
    citizenship_status: CitizenshipStatus = CitizenshipStatus.CITIZEN

    # Persona fields (Faker-generated, never real)
    head_of_household_name: str = ""
    age_of_head: int = 35
    city: str = ""
    zip_code: str = ""

    # Income breakdown
    earned_income: float | None = None  # Portion of gross that is earned wages
    unearned_income: float = 0.0  # SSI, child support, etc.
    shelter_costs: float | None = None  # Monthly rent + utilities

    # Program-specific extras
    extra: dict[str, Any] = field(default_factory=dict)

    # Special population flags (all default to False/None — backward compatible)
    is_homeless: bool = False
    student_status: str | None = None  # None | "enrolled_half_time" | "enrolled_full_time"
    is_boarder: bool = False
    is_migrant_worker: bool = False
    has_ineligible_members: bool = False  # mixed-status HH
    ineligible_member_count: int = 0

    # Provenance: the ACS vintage a 'realistic' profile was sampled from (e.g.
    # 'acs5-2024'), or None for other strategies / built-in fallback numbers.
    # Deliberately not in `extra`, which `to_scenario_fields` copies into the
    # scenario the model sees.
    census_vintage: str | None = None
    # The calendar year whose dollars `monthly_gross_income` is stated in, for
    # 'realistic' profiles (the census vintage's year unless restated); else None.
    income_dollar_year: int | None = None
    # Which census model drew a 'realistic' profile: "pums_household_types" (joint
    # household types from ACS PUMS, #8) or "acs_marginals" (independent per-trait
    # summary-table rates); None for other strategies / built-in fallback numbers.
    household_model: str | None = None
    # For 'caseload' profiles: the household's countable income sources in the SNAP QC
    # model (subset of "earned", "ssi", "social_security"). Provenance only -- not
    # rendered into the scenario.
    income_sources: tuple[str, ...] | None = None

    def __post_init__(self) -> None:
        if not self.head_of_household_name:
            self.head_of_household_name = _faker.name()
        if not self.city:
            self.city = _faker.city()
        if not self.zip_code:
            self.zip_code = _faker.zipcode()
        if self.earned_income is None:
            self.earned_income = self.monthly_gross_income
        # A household whose HEAD is 60+ definitionally contains an elderly
        # member (7 CFR 271.2 defines "elderly member" as age 60 or older), so
        # `has_elderly_or_disabled=False` alongside `age_of_head >= 60` is not a
        # different household -- it is a contradiction, and one the rendered
        # prose puts in front of the model ("Kurt Oconnell is a 63-year-old
        # single parent...") while the expected reasoning applies the gross
        # income test that 7 CFR 273.9(a)(2) waives for such households.
        #
        # Measured before this guard: 14% of SNAP threshold profiles. A model
        # fine-tuned on that corpus read the stated age, correctly inferred
        # elderly status, and was penalized against a label that said otherwise
        # -- then degenerated into repetition loops on exactly those cases at
        # eval time. The reasoning was right and the ground truth was wrong.
        #
        # One-directional on purpose: the flag may be True with a head under 60
        # (a disabled member, or an elderly member who is not the head). Only
        # the 60+/False combination is contradictory. Raise rather than coerce
        # -- silently flipping the flag would relabel a case that was sampled to
        # anchor on the gross income test onto a test that no longer binds.
        if self.age_of_head >= 60 and not self.has_elderly_or_disabled:
            raise ValueError(
                f"age_of_head={self.age_of_head} implies the household contains an elderly "
                f"member (7 CFR 271.2: age 60+), but has_elderly_or_disabled=False. "
                f"Sample age_of_head below 60 for a non-elderly household, or set the flag."
            )

    @classmethod
    def random(
        cls,
        state: str = "VA",
        seed: int | None = None,
        strategy: str = "uniform",
        census_vintage: CensusVintage | int | str | None = None,
        income_dollar_year: int | None = None,
        population: str = "general",
    ) -> USHouseholdProfile:
        """Generate a random profile using the given strategy.

        Args:
            state: Two-letter state code.
            seed: RNG seed for reproducibility.
            strategy: 'uniform' samples freely; 'realistic' uses ACS-based weights.
            census_vintage: ACS release to sample a 'realistic' profile from --
                a year (5-year estimates ending that year), 'acs1-2025', or a
                CensusVintage. None uses DEFAULT_CENSUS_VINTAGE.
            income_dollar_year: For 'realistic' profiles, restate income in this
                calendar year's dollars using CPI-U (census incomes are in the
                vintage's own dollars). None leaves them in the vintage's dollars.
            population: For 'realistic' profiles, 'general' (default) samples the
                whole population from the ACS; 'caseload' samples households that
                actually receive SNAP, from the SNAP Quality Control tables (#9).
                Caseload incomes are placed against the poverty guideline of the
                SNAP fiscal year `income_dollar_year` (default: the census vintage's
                year), so they sit where real caseload incomes sit relative to
                that year's limits.

        Raises:
            ValueError: If `census_vintage` or `income_dollar_year` is given with a
                strategy other than 'realistic' (only that strategy reads census
                data), or a vintage has no data for this state, or `population`
                is unknown or 'caseload' with another strategy.
        """
        if population not in POPULATIONS:
            raise ValueError(f"population must be one of {POPULATIONS}, got {population!r}")
        if population != "general" and strategy != "realistic":
            raise ValueError(f"population={population!r} only applies to strategy='realistic'")
        for name, value in (("census_vintage", census_vintage), ("income_dollar_year", income_dollar_year)):
            if value is not None and strategy != "realistic":
                raise ValueError(
                    f"{name} only applies to strategy='realistic' (got strategy='{strategy}'); "
                    "other strategies don't sample from census data."
                )
        rng = random.Random(seed)
        if seed is not None:
            Faker.seed(seed)

        if strategy == "realistic" and population == "caseload":
            return _build_caseload_profile(
                state=state, rng=rng, census_vintage=census_vintage, income_dollar_year=income_dollar_year
            )
        if strategy == "realistic":
            return _build_realistic_profile(
                state=state, rng=rng, census_vintage=census_vintage, income_dollar_year=income_dollar_year
            )

        # uniform (default): national-level approximations
        hh_size = rng.choices(
            [1, 2, 3, 4, 5, 6],
            weights=[0.28, 0.34, 0.16, 0.13, 0.06, 0.03],
        )[0]

        # Monthly gross income: roughly lognormal, median ~$3,500
        gross = round(rng.lognormvariate(8.1, 0.7), -1)  # round to nearest 10
        gross = min(max(gross, 0), 15000)

        has_elderly = rng.random() < 0.15
        has_children = rng.random() < 0.35 if hh_size > 1 else False

        return cls(
            household_size=hh_size,
            monthly_gross_income=float(gross),
            state=state.upper(),
            liquid_assets=round(rng.uniform(0, 5000), -2),
            has_elderly_or_disabled=has_elderly,
            has_dependent_children=has_children,
            age_of_head=_age_consistent_with(has_elderly, rng, young=(22, 72)),
            shelter_costs=round(rng.uniform(600, 2500), -1),
        )

    @classmethod
    def at_threshold(
        cls,
        program: str,
        threshold: str,
        state: str,
        household_size: int,
        fiscal_year: int = 2026,
        offset_pct: float = 0.0,
        seed: int | None = None,
    ) -> USHouseholdProfile:
        """Build a profile at a specific policy threshold boundary.

        This factory is the core edge-case generation mechanism. It places
        the household's income or assets exactly at (or just above/below)
        a program threshold.

        Args:
            program: 'snap', 'wic', 'medicaid', etc.
            threshold: Named threshold type. See THRESHOLD_REGISTRY.
            state: Two-letter state code.
            household_size: Number of people in household.
            fiscal_year: Federal FY or calendar year for the program.
            offset_pct: How far from the threshold boundary to place the profile.
                0.0  = exactly at limit
                0.01 = 1% above limit  (should be ineligible for income tests)
               -0.01 = 1% below limit  (should be eligible)
                0.35 = 35% above limit (clearly ineligible, not a boundary case)
               -0.35 = 35% below limit (clearly eligible, not a boundary case)
            seed: RNG seed.

        Returns:
            USHouseholdProfile with income/assets precisely set relative to threshold.
        """
        rng = random.Random(seed)
        if seed is not None:
            Faker.seed(seed)

        if program == "snap":
            return _build_snap_threshold_profile(
                threshold=threshold,
                state=state,
                household_size=household_size,
                fiscal_year=fiscal_year,
                offset_pct=offset_pct,
                rng=rng,
            )
        elif program == "wic":
            return _build_wic_threshold_profile(
                threshold=threshold,
                state=state,
                household_size=household_size,
                fiscal_year=fiscal_year,
                offset_pct=offset_pct,
                rng=rng,
            )
        else:
            raise NotImplementedError(f"at_threshold not yet implemented for program '{program}'")

    def to_scenario_fields(self) -> dict[str, Any]:
        """Return fields suitable for populating a ScenarioBlock."""
        return {
            "household_size": self.household_size,
            "monthly_gross_income": self.monthly_gross_income,
            "monthly_net_income": self.monthly_net_income,
            "liquid_assets": self.liquid_assets,
            "state": self.state,
            "has_elderly_or_disabled": self.has_elderly_or_disabled,
            "has_dependent_children": self.has_dependent_children,
            "citizenship_status": self.citizenship_status.value,
            "additional_context": {
                "head_name": self.head_of_household_name,
                "age_of_head": self.age_of_head,
                "city": self.city,
                "earned_income": self.earned_income,
                "unearned_income": self.unearned_income,
                "shelter_costs": self.shelter_costs,
                **self.extra,
            },
        }

    def natural_language_summary(self, program: str = "snap") -> str:
        """Generate a natural language scenario description for this profile."""
        age_desc = f"{self.age_of_head}-year-old"
        hh_desc = _household_description(self.household_size, self.has_dependent_children)
        income_desc = f"${self.monthly_gross_income:,.0f}/month gross income"
        asset_desc = f"${self.liquid_assets:,.0f} in savings" if self.liquid_assets > 0 else "no significant savings"
        elderly_desc = " One household member is elderly (age 60+) or disabled." if self.has_elderly_or_disabled else ""
        citizenship_desc = (
            ""
            if self.citizenship_status == CitizenshipStatus.CITIZEN
            else (f" {self.head_of_household_name} is a {self.citizenship_status.value.replace('_', ' ')}.")
        )

        return (
            f"{self.head_of_household_name} is a {age_desc} {hh_desc}"
            f" in {self.city}, {self.state}. "
            f"Their household has {income_desc} and {asset_desc}.{elderly_desc}{citizenship_desc}"
        )

    def natural_language_summary_styled(self, style: str, program: str = "snap") -> str:
        """`natural_language_summary`, in a different register, same facts.

        Exists because every scenario in this kit currently renders through
        that ONE sentence template. Measured on the SNAP CoT fine-tune corpus
        (see the RLVR post-mortem in the Nava Work Vault), that is 7,402
        training records that all read alike -- one system prompt covering
        100% of them, and only ~4,300 distinct masked-number templates for
        7,402 records. Published 2026 findings on RLVR training report
        measured generalization gains from prompt-side diversity (roughly
        +1.8pp in-domain, +2.6pp out-of-domain in one study), and separately
        warn that low diversity drives "diversity collapse" during RL
        training. This method is the mechanism for that diversity: same
        `USHouseholdProfile`, several genuinely different renderings.

        Every style below states the SAME facts as `natural_language_summary`
        -- name, age, household composition, city/state, gross income, assets,
        the elderly/disabled flag, citizenship status when non-citizen -- and
        renders every number identically (`f"{x:,.0f}"` on the same field), so
        no downstream consumer (a reward function, a human grader, a model
        being trained) can read a different fact out of a different style.
        Only sentence structure, ordering, and register vary. Dropping a fact
        in one style but not another would silently make some training
        records easier than others for a reason that has nothing to do with
        SNAP policy -- see `test_all_styles_state_the_same_facts` in
        test_us_household_profile.py, which is what actually guards this.

        Raises ValueError for an unrecognized `style` rather than falling back
        to the default silently -- a typo'd style name should fail loudly, not
        quietly collapse the requested diversity back to one template.
        """
        if style not in PHRASING_STYLES:
            raise ValueError(f"unknown phrasing style {style!r}; choose one of {PHRASING_STYLES}")

        hh_desc = _household_description(self.household_size, self.has_dependent_children)
        assets_present = self.liquid_assets > 0
        elderly = self.has_elderly_or_disabled
        noncitizen = self.citizenship_status != CitizenshipStatus.CITIZEN
        citizenship_label = self.citizenship_status.value.replace("_", " ")

        if style == "caseworker_note":
            lines = [
                f"Applicant: {self.head_of_household_name}, age {self.age_of_head}.",
                f"Household: {hh_desc}, located in {self.city}, {self.state}.",
                f"Gross income: ${self.monthly_gross_income:,.0f}/month.",
                f"Liquid assets: ${self.liquid_assets:,.0f}." if assets_present else "Liquid assets: none reported.",
            ]
            if elderly:
                lines.append("Elderly or disabled household member: yes (age 60+ or disabled).")
            if noncitizen:
                lines.append(f"Citizenship status: {citizenship_label}.")
            return " ".join(lines)

        if style == "narrative":
            opening = (
                f"In {self.city}, {self.state}, {self.head_of_household_name}, {self.age_of_head} years old, "
                f"heads a household best described as a {hh_desc}."
            )
            money = f"Every month the household brings in ${self.monthly_gross_income:,.0f} in gross income, " + (
                f"against ${self.liquid_assets:,.0f} held in savings."
                if assets_present
                else "with no meaningful savings to draw on."
            )
            extra = ""
            if elderly:
                extra += " Someone in the household is age 60 or older, or disabled."
            if noncitizen:
                extra += f" {self.head_of_household_name} holds {citizenship_label} status."
            return f"{opening} {money}{extra}"

        if style == "terse":
            parts = [
                f"{self.head_of_household_name}",
                f"age {self.age_of_head}",
                hh_desc,
                f"{self.city}, {self.state}",
                f"${self.monthly_gross_income:,.0f}/mo gross",
                f"${self.liquid_assets:,.0f} savings" if assets_present else "no savings",
            ]
            if elderly:
                parts.append("elderly/disabled member")
            if noncitizen:
                parts.append(citizenship_label)
            return "; ".join(parts) + "."

        if style == "conversational":
            text = (
                f"So here's the situation: {self.head_of_household_name} is {self.age_of_head}, lives in "
                f"{self.city}, {self.state}, and the household is a {hh_desc}. Money-wise, they're bringing home "
                f"about ${self.monthly_gross_income:,.0f} a month, and "
                + (
                    f"they've got ${self.liquid_assets:,.0f} put away in savings."
                    if assets_present
                    else "they don't really have savings to speak of."
                )
            )
            if elderly:
                text += " Also worth noting, someone in the household is 60 or older, or disabled."
            if noncitizen:
                text += f" {self.head_of_household_name} is a {citizenship_label}."
            return text

        # style == "formal"
        text = (
            f"The applicant, {self.head_of_household_name}, is {self.age_of_head} years of age and resides in "
            f"{self.city}, {self.state}, as the head of a household constituting a {hh_desc}. The household's "
            f"monthly gross income is ${self.monthly_gross_income:,.0f}, and its liquid assets are "
            + (f"${self.liquid_assets:,.0f}." if assets_present else "not significant.")
        )
        if elderly:
            text += " A member of the household is elderly (age 60 or older) or disabled."
        if noncitizen:
            text += f" The applicant holds {citizenship_label} status."
        return text

    def generate_scenario_question_styled(self, style: str, program: str = "snap") -> str:
        """Generate an eligibility determination question in a specific phrasing style.

        All styles ask the same underlying question about eligibility but from different angles
        and registers. They state identical facts (income, assets, household composition) but vary
        in framing, terminology, and reasoning focus. This supports semantic variation for RLVR
        training: the model cannot memorize surface patterns when the same underlying scenario is
        expressed multiple ways with consistent outcomes.

        Args:
            style: One of SCENARIO_PHRASING_STYLES
            program: Benefits program, e.g. 'snap', 'wic', 'medicaid'

        Raises:
            ValueError: If style is not recognized.

        Returns:
            A question string in the requested style.
        """
        if style not in SCENARIO_PHRASING_STYLES:
            raise ValueError(f"unknown scenario phrasing style {style!r}; choose one of {SCENARIO_PHRASING_STYLES}")

        if style == "direct":
            return (
                f"Is this household eligible for {program.upper()} benefits? "
                f"Show your reasoning step by step, citing relevant federal regulations."
            )

        if style == "exploratory":
            return (
                f"What factors determine whether this household qualifies for {program.upper()}? "
                "Walk through the relevant eligibility criteria and explain how this household "
                "meets or fails each one."
            )

        if style == "constraint_focused":
            return (
                f"Evaluate this household against the key constraints for {program.upper()} eligibility. "
                "What income limits, asset limits, and other thresholds apply? "
                "Where does this household stand relative to each?"
            )

        if style == "outcome_focused":
            return (
                "Based on the household's situation, what would be your eligibility determination "
                f"for {program.upper()}? "
                f"Provide the specific policy justification and reference the applicable regulations."
            )

        # style == "policy_grounded"
        return (
            f"Using federal policy regulations, determine {program.upper()} eligibility for this household. "
            "Cite the specific CFR sections that apply and explain how this household's circumstances "
            "align with or diverge from the requirements."
        )


def _age_consistent_with(has_elderly: bool, rng: random.Random, *, young: tuple[int, int]) -> int:
    """Sample a head-of-household age that cannot contradict `has_elderly`.

    `USHouseholdProfile.__post_init__` rejects `age_of_head >= 60` alongside
    `has_elderly_or_disabled=False` (7 CFR 271.2). Sampling the age from a range
    chosen by the flag keeps every construction site on the legal side of that
    invariant instead of relying on each call site to remember it.
    """
    return rng.randint(60, 85) if has_elderly else rng.randint(young[0], min(young[1], 59))


# Monthly income above which a 'realistic' draw is redrawn ($600,000/year in the vintage's dollars).
_REALISTIC_INCOME_CAP = 50_000.0


def _build_realistic_profile(
    state: str,
    rng: random.Random,
    census_vintage: CensusVintage | int | str | None = None,
    income_dollar_year: int | None = None,
) -> USHouseholdProfile:
    """Build a profile sampled from Census ACS state-level distributions.

    Falls back to hardcoded national weights if the default vintage has no
    census data file (warning already emitted by CensusDataSource.load()). An
    explicitly requested vintage with no data raises instead.
    """
    from govsynth.sources.us.census import CensusDataSource

    dist = CensusDataSource(state, vintage=census_vintage).load()

    if dist is None:
        # No census data available -- silent fallback to national approximations
        hh_size = rng.choices([1, 2, 3, 4, 5, 6], weights=[0.28, 0.34, 0.16, 0.13, 0.06, 0.03])[0]
        gross = min(max(round(rng.lognormvariate(8.1, 0.7), -1), 0), 15000)
        fallback_has_elderly = rng.random() < 0.15
        return USHouseholdProfile(
            household_size=hh_size,
            monthly_gross_income=float(gross),
            state=state.upper(),
            liquid_assets=round(rng.uniform(0, 5000), -2),
            has_elderly_or_disabled=fallback_has_elderly,
            has_dependent_children=rng.random() < 0.35 if hh_size > 1 else False,
            age_of_head=_age_consistent_with(fallback_has_elderly, rng, young=(22, 72)),
            shelter_costs=round(rng.uniform(600, 2500), -1),
        )

    from govsynth.sources.us.household_types import load_household_types

    types = load_household_types(state, dist.vintage)
    if types is not None:
        return _build_from_household_types(state, rng, dist, types, income_dollar_year)

    # Step 3: household size from ACS weights
    hh_size = rng.choices(list(range(1, 7)), weights=dist.household_size_weights)[0]

    # Step 4: monthly gross income -- lognormal fitted to ACS income brackets, in the
    # vintage's dollars. Draws above the cap are redrawn rather than clamped: clamping
    # used to put ~21% of profiles at exactly $15,000/month once the top income brackets
    # were labeled correctly (#11). The cap only trims the fitted lognormal's extreme tail.
    draw = _REALISTIC_INCOME_CAP
    for _ in range(50):
        candidate = rng.lognormvariate(dist.income_mu, dist.income_sigma)
        if candidate <= _REALISTIC_INCOME_CAP:
            draw = candidate
            break
    dollar_year = dist.dollar_year
    if income_dollar_year is not None and dollar_year is not None:
        from govsynth.sources.us.cpi import inflation_factor

        draw *= inflation_factor(dollar_year, income_dollar_year)
        dollar_year = income_dollar_year
    gross = max(round(draw, -1), 0)

    # Step 5: age of householder -- Normal(mu, sigma) fitted to ACS B25007, clamped to [18, 80].
    # Drawn before the elderly/disabled flag so the flag can be conditioned on it.
    age = max(18, min(80, round(rng.normalvariate(dist.age_mu, dist.age_sigma))))

    # Step 6: household demographics.
    # pct_with_children is the share of ALL households with someone under 18
    # (ACS B11005). One-person households can't have children, so the rate
    # among multi-person households is pct / P(size > 1).
    p_multi = 1.0 - dist.household_size_weights[0] / (sum(dist.household_size_weights) or 1.0)
    p_children_given_multi = min(1.0, dist.pct_with_children / p_multi) if p_multi > 0 else 0.0
    has_children = rng.random() < p_children_given_multi if hh_size > 1 else False

    # A householder aged 60+ makes the household elderly by definition
    # (7 CFR 271.2). pct_elderly_or_disabled is the household-level target
    # share; to hit it overall rather than overshoot, the independent draw only
    # covers the remainder (a disabled member, or an elderly non-head) among
    # households whose head is under 60.
    p_head_60_plus = 1.0 - NormalDist(dist.age_mu, max(dist.age_sigma, 1e-6)).cdf(59.5)
    p_extra = 0.0
    if p_head_60_plus < 1.0:
        p_extra = max(0.0, (dist.pct_elderly_or_disabled - p_head_60_plus) / (1.0 - p_head_60_plus))
    has_elderly = age >= 60 or rng.random() < p_extra

    # Step 7: citizenship status
    roll = rng.random()
    if roll < dist.pct_citizen:
        citizenship = CitizenshipStatus.CITIZEN
    elif roll < dist.pct_citizen + dist.pct_noncitizen_eligible:
        citizenship = CitizenshipStatus.QUALIFIED_ALIEN
    else:
        citizenship = CitizenshipStatus.NON_QUALIFIED_ALIEN

    # Step 8: earned vs. unearned income split. Prefer the household-level share
    # with any earnings (ACS B19051); fall back to the person-level labor force
    # participation rate for census files written before that field existed.
    p_earnings = (
        dist.pct_households_with_earnings
        if dist.pct_households_with_earnings is not None
        else dist.labor_force_participation_rate
    )
    earned = float(gross) if rng.random() < p_earnings else 0.0
    unearned = float(gross) - earned

    # Step 9: shelter costs -- renters vs. owners
    if rng.random() < dist.pct_renter:
        sigma = dist.median_gross_rent_monthly * 0.3
        shelter = max(0.0, round(rng.normalvariate(dist.median_gross_rent_monthly, sigma), -1))
    else:
        shelter = round(rng.uniform(400, 1200), -1)

    # dist.pct_social_security, dist.pct_ssi, dist.pct_public_assistance are available
    # for future income-source enrichment (e.g. flagging SSI/SSDI receipt on the profile).

    return USHouseholdProfile(
        household_size=hh_size,
        monthly_gross_income=float(gross),
        state=state.upper(),
        liquid_assets=round(rng.uniform(0, 3000), -2),
        has_elderly_or_disabled=has_elderly,
        has_dependent_children=has_children,
        citizenship_status=citizenship,
        earned_income=earned,
        unearned_income=unearned,
        shelter_costs=shelter,
        age_of_head=age,
        census_vintage=dist.vintage,
        income_dollar_year=dollar_year,
        household_model="acs_marginals",
    )


def _build_from_household_types(
    state: str,
    rng: random.Random,
    dist: CensusDistribution,
    types: HouseholdTypes,
    income_dollar_year: int | None,
) -> USHouseholdProfile:
    """Build a realistic profile from a joint PUMS household type (#8).

    Size, income band, elderly/disabled, children, earnings, head citizenship and
    head age band come from one weighted type, so their correlations are kept.
    Values within the type (exact income, age, earned share) are drawn
    synthetically; shelter costs and assets still come from the summary file.
    """
    t = types.sample(rng)
    annual = types.draw_annual_income(t, rng)
    dollar_year = int(types.raw["_metadata"]["dollar_year"])
    if income_dollar_year is not None:
        from govsynth.sources.us.cpi import inflation_factor

        annual *= inflation_factor(dollar_year, income_dollar_year)
        dollar_year = income_dollar_year
    gross = max(round(annual / 12, -1), 0.0)
    age = types.draw_head_age(t, rng)

    if t.head_citizen:
        citizenship = CitizenshipStatus.CITIZEN
    elif rng.random() < dist.pct_noncitizen_eligible / max(1.0 - dist.pct_citizen, 1e-9):
        # Same qualified share of non-citizens as the summary file applies.
        citizenship = CitizenshipStatus.QUALIFIED_ALIEN
    else:
        citizenship = CitizenshipStatus.NON_QUALIFIED_ALIEN

    # A type with earnings but zero/negative income gets earned = gross (= 0); the
    # earned flag below then reflects only positive earned dollars.
    earned = round(gross * t.earned_share, -1) if t.earns else 0.0
    if t.earns and gross > 0 and earned <= 0:
        earned = min(10.0, gross)
    unearned = float(gross) - earned

    if rng.random() < dist.pct_renter:
        sigma = dist.median_gross_rent_monthly * 0.3
        shelter = max(0.0, round(rng.normalvariate(dist.median_gross_rent_monthly, sigma), -1))
    else:
        shelter = round(rng.uniform(400, 1200), -1)

    return USHouseholdProfile(
        household_size=t.size,
        monthly_gross_income=float(gross),
        state=state.upper(),
        liquid_assets=round(rng.uniform(0, 3000), -2),
        has_elderly_or_disabled=t.eld_dis,
        has_dependent_children=t.kids,
        citizenship_status=citizenship,
        earned_income=float(earned),
        unearned_income=unearned,
        shelter_costs=shelter,
        age_of_head=age,
        census_vintage=dist.vintage,
        income_dollar_year=dollar_year,
        household_model="pums_household_types",
    )


def _build_caseload_profile(
    state: str,
    rng: random.Random,
    census_vintage: CensusVintage | int | str | None,
    income_dollar_year: int | None,
) -> USHouseholdProfile:
    """Build a profile of a household that receives SNAP, from the QC caseload tables (#9).

    One caseload cell fixes children, elderly/disabled group, size, gross income as a
    percent of poverty, and income sources. Within it: income is uniform over the
    poverty bin (the open top bin's upper end is calibrated per state to the
    report's mean gross income); earned income is all of gross for earners without SSI or Social
    Security and half of it for those with either (the report gives source shares,
    not amounts per household); countable resources are nonzero for 1.6% of
    households (Table A.17), averaging $550 (Table A.5). Shelter costs follow the
    state's ACS rents. A one-person cell with children (a child-only SNAP unit) is
    rendered without dependent children, since the profile has no adult to parent them.
    """
    import warnings

    from govsynth.sources.us.census import CensusDataSource, CensusVintage
    from govsynth.sources.us.snap_caseload import DEFAULT_QC_FY, caseload_table, poverty_guideline_annual

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        dist = CensusDataSource(state, vintage=census_vintage).load()
    if dist is None:
        if census_vintage is not None:
            raise ValueError(f"No census data for {state} in vintage {census_vintage}")
        vintage_year = None
    else:
        vintage_year = CensusVintage.parse(dist.vintage).year if dist.vintage else None
    fiscal_year = income_dollar_year or vintage_year or DEFAULT_QC_FY
    table = caseload_table(state, DEFAULT_QC_FY)
    cell = table.sample(rng)

    lo, hi = table.income_range_pct(cell.pov)
    fpl = poverty_guideline_annual(cell.size, state, fiscal_year - 1)  # SNAP FY Y uses year Y-1 guidelines
    gross = 0.0 if hi == 0 else max(1.0, float(round(rng.uniform(lo, hi) / 100 * fpl / 12)))
    sources = tuple(
        name for name, flag in (("earned", cell.earned), ("ssi", cell.ssi), ("social_security", cell.social_security))
        if flag
    )  # fmt: skip
    if not cell.earned:
        earned = 0.0
    elif cell.ssi or cell.social_security:
        earned = float(round(gross / 2))
    else:
        earned = gross

    elderly = cell.group == "elderly"
    age = rng.randint(60, 85) if elderly else rng.randint(18, 59)
    noncitizen_share = table.qc["states"].get(state.upper(), {}).get("pct_noncitizen_participants", 0.0) / 100
    citizenship = CitizenshipStatus.QUALIFIED_ALIEN if rng.random() < noncitizen_share else CitizenshipStatus.CITIZEN
    assets = float(round(rng.uniform(1, 1100), -1)) if rng.random() < 0.016 else 0.0
    if dist is not None and rng.random() < dist.pct_renter:
        sigma = dist.median_gross_rent_monthly * 0.3
        shelter = max(0.0, round(rng.normalvariate(dist.median_gross_rent_monthly, sigma), -1))
    else:
        shelter = round(rng.uniform(400, 1200), -1)

    return USHouseholdProfile(
        household_size=cell.size,
        monthly_gross_income=gross,
        state=state.upper(),
        liquid_assets=assets,
        has_elderly_or_disabled=cell.group != "none",
        has_dependent_children=bool(cell.kids) and cell.size > 1,
        citizenship_status=citizenship,
        earned_income=earned,
        unearned_income=gross - earned,
        shelter_costs=shelter,
        age_of_head=age,
        census_vintage=dist.vintage if dist is not None else None,
        income_dollar_year=fiscal_year,
        household_model=f"snap_qc_fy{table.fiscal_year}",
        income_sources=sources,
    )


